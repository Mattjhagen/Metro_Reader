import JSZip from 'jszip';
import { Book } from '../types';

/**
 * Downloads all converted chapters merged into a single MP3 file
 */
export async function downloadCompleteAudiobookMp3(book: Book): Promise<void> {
  const convertedChapters = book.chapters.filter((ch) => ch.audioBlob || ch.audioUrl);
  if (convertedChapters.length === 0) {
    throw new Error('No audio chapters available to download.');
  }

  const audioBlobs: Blob[] = [];

  for (const ch of convertedChapters) {
    if (ch.audioBlob) {
      audioBlobs.push(ch.audioBlob);
    } else if (ch.audioUrl) {
      const res = await fetch(ch.audioUrl);
      const b = await res.blob();
      audioBlobs.push(b);
    }
  }

  // Concatenate all audio blobs into a single continuous MP3 blob
  const mergedBlob = new Blob(audioBlobs, { type: 'audio/mpeg' });
  const downloadUrl = URL.createObjectURL(mergedBlob);

  const cleanTitle = book.title.replace(/[^a-zA-Z0-9_-]/g, '_');
  const a = document.createElement('a');
  a.href = downloadUrl;
  a.download = `${cleanTitle}_Complete_Audiobook.mp3`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(downloadUrl), 10000);
}

/**
 * Downloads a ZIP archive containing individual chapter MP3 files + book metadata
 */
export async function downloadAudiobookZip(
  book: Book,
  onProgress?: (percent: number) => void
): Promise<void> {
  const convertedChapters = book.chapters.filter((ch) => ch.audioBlob || ch.audioUrl);
  if (convertedChapters.length === 0) {
    throw new Error('No audio chapters available to package into ZIP.');
  }

  const zip = new JSZip();
  const folderName = `${book.title.replace(/[^a-zA-Z0-9_-]/g, '_')}_Audiobook`;
  const folder = zip.folder(folderName) || zip;

  // Add individual chapter audio files
  for (let i = 0; i < convertedChapters.length; i++) {
    const ch = convertedChapters[i];
    let blob: Blob;

    if (ch.audioBlob) {
      blob = ch.audioBlob;
    } else {
      const res = await fetch(ch.audioUrl!);
      blob = await res.blob();
    }

    const chapterIndexPadded = (i + 1).toString().padStart(2, '0');
    const safeChapterTitle = ch.title.replace(/[^a-zA-Z0-9_-]/g, '_');
    const fileName = `${chapterIndexPadded}_${safeChapterTitle}.mp3`;

    folder.file(fileName, blob);
    if (onProgress) {
      onProgress(Math.round(((i + 1) / convertedChapters.length) * 80));
    }
  }

  // Add metadata README text
  const readmeContent = `Audiobook: ${book.title}
Author: ${book.author}
Total Chapters: ${convertedChapters.length}
Format: MP3 Audio
Generated by Metro Reader - Minimalist Audiobook Studio
Date: ${new Date().toLocaleDateString()}

Tracklist:
${convertedChapters
  .map(
    (ch, i) =>
      `${(i + 1).toString().padStart(2, '0')}. ${ch.title} (${Math.round(
        ch.wordCount
      )} words)`
  )
  .join('\n')}
`;
  folder.file('README.txt', readmeContent);

  // Generate zip file
  const zipBlob = await zip.generateAsync(
    { type: 'blob', compression: 'DEFLATE' },
    (metadata) => {
      if (onProgress) {
        onProgress(80 + Math.round(metadata.percent * 0.2));
      }
    }
  );

  const cleanTitle = book.title.replace(/[^a-zA-Z0-9_-]/g, '_');
  const downloadUrl = URL.createObjectURL(zipBlob);
  const a = document.createElement('a');
  a.href = downloadUrl;
  a.download = `${cleanTitle}_Audiobook_Chapters.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(downloadUrl), 10000);
}
